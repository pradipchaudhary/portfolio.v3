// Dots (x, y, radius) pop in once the pen finishes.
const DOTS: [number, number, number][] = [
  [867.2, 740.1, 7.5],
  [796.7, 798.6, 7.2],
];

export default function SignatureText({
  delay = 0.9,
  drawDuration = 2.5,
  className = "text-gray-700 dark:text-zinc-300 transition-colors duration-300",
}: SignatureTextProps) {
  const reduceMotion = useReducedMotion();

  let elapsed = 0;
  const timed = STROKES.map((s) => {
    const start = delay + elapsed;
    const duration = s.share * drawDuration;
    elapsed += duration;
    return { ...s, start, duration };
  });
  const dotsStart = delay + drawDuration;

  return (
    <svg
      role="img"
      aria-label="Signature"
      width="110"
      height="70"
      viewBox={VIEW_BOX}
      className={`${className} select-none mt-8 `}
      fill="none"
      stroke="currentColor"
      strokeWidth={STROKE_WIDTH}
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {timed.map((s, i) => (
        <motion.path
          key={i}
          d={s.d}
          // opacity stays 0 until the pen reaches the stroke, so round caps don't show as stray dots.
          initial={{ pathLength: reduceMotion ? 1 : 0, opacity: 0 }}
          animate={{ pathLength: 1, opacity: 1 }}
          transition={
            reduceMotion
              ? { delay, duration: 0.5 }
              : {
                  pathLength: {
                    delay: s.start,
                    duration: s.duration,
                    ease: "linear",
                  },
                  opacity: { delay: s.start, duration: 0.01 },
                }
          }
        />
      ))}
      {DOTS.map(([cx, cy, r], i) => (
        <motion.circle
          key={i}
          cx={cx}
          cy={cy}
          r={r}
          fill="currentColor"
          stroke="none"
          initial={{ opacity: 0, scale: reduceMotion ? 1 : 0 }}
          animate={{ opacity: 1, scale: 1 }}
          transition={{
            delay: reduceMotion ? delay : dotsStart + i * 0.1,
            duration: 0.2,
          }}
          style={{ transformBox: "fill-box", transformOrigin: "center" }}
        />
      ))}
    </svg>
  );
}
